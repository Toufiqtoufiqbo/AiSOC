"""
Detection Pack — SaaS content depth (Box, Dropbox, 1Password)
=============================================================

Depth plan 3.6 asks that *"every SaaS source with a connector … has at
least 20"* executable conditions. Three of the named sources had **zero**:
a customer could connect Box, Dropbox or 1Password, see the events arrive,
and get no detections at all. That is the sharpest kind of gap in this
corpus, because the connector works and the product looks attached.

Field reachability, checked before authoring rather than after
---------------------------------------------------------------
These connectors emit a thin envelope — `source`, `severity`, `actor`,
`actor_email`, `src_ip`, `event_type`, `target`, `created_at` — with the
vendor's own payload under `raw_event`. The detection engine flattens
`raw_event` exactly one level, so the vendor's top-level keys are in the
match namespace and its nested objects are not.

Every clause below was checked against the namespace
`scripts/check_detection_fields.py` recovers before the rule was written,
which is the opposite order from the one that produced seven unfireable
Okta rules. Two consequences are visible in the content: nothing matches on
`created_by`, `action_by` or `client`, because those are **dicts** one level
down and comparing a dict to a string is the documented way a rule silently
never fires; and 1Password rules key on `category` and `type`, which are
genuine top-level keys of its sign-in event.

Event names are the vendors' own
---------------------------------
Box event types (`ITEM_DOWNLOAD`, `SHIELD_ALERT`, `ROLE_CHANGE_TO_ADMIN`)
and Dropbox event tags (`shared_content_change_link_audience_to_public`,
`member_change_admin_role`) are taken from the connectors' own risk tables,
not invented. A plausible-looking event name that the vendor does not emit
is the same defect as an unreachable field wearing a different hat.

Fixtures
--------
Hand-authored, both halves, for the reason the 3.5 family documents: the
`S()` synthesiser derives the positive from the clause, which makes replay
tautological, and inverts the negative to `not-<value>`, which measures
nothing about false positives. Each negative here is ordinary benign
traffic of the same shape — the internal collaborator rather than the
external one, the successful sign-in rather than the failed one, the
expected admin rather than the unexpected one.
"""

